def build_mjcf(params: ArmParams | None = None, *, meshdir: str | None = None) -> str:
    """Generate MJCF. ``meshdir`` defaults to the path relative to the written file.

    A model compiled from a *string* has no file to be relative to, so
    MuJoCo cannot resolve ``../../cad/export``. Callers that compile in memory
    (``MujocoArm(from_params=True)``) must pass an absolute path instead.
    """
    params = params or default_params()
    root = ET.Element("mujoco", model=params.meta.name)

    ET.SubElement(root, "compiler", angle="radian", meshdir=meshdir or MESH_RELATIVE)

    # Visual meshes exported from the CAD. Collision stays on the capsules
    # below: convexified meshes are slower and buy nothing for an arm whose
    # links are convex-ish anyway. Separating visual from collision geometry is
    # standard practice, not a shortcut.
    if _meshes_available():
        assets = ET.SubElement(root, "asset")
        for _, link, _, _, _ in _chain(params):
            ET.SubElement(assets, "mesh", name=f"{link.name}_mesh", file=f"{link.name}.stl")
    ET.SubElement(
        root,
        "option",
        timestep=_fmt(params.sim.timestep_s),
        gravity=_vec(params.sim.gravity_ms2),
        integrator="implicitfast",
    )

    defaults = ET.SubElement(root, "default")
    ET.SubElement(defaults, "geom", rgba="0.5 0.6 0.7 1", contype="1", conaffinity="1")
    # No default joint block: armature and damping are per-actuator and are
    # written onto each joint from config/arm.toml.

    worldbody = ET.SubElement(root, "worldbody")
    ET.SubElement(worldbody, "light", pos="0 0 1.5", dir="0 0 -1", diffuse="0.8 0.8 0.8")
    ET.SubElement(
        worldbody,
        "geom",
        name="floor",
        type="plane",
        size="1 1 0.05",
        rgba="0.25 0.26 0.28 1",
    )

    # Static obstacles, welded to the world. Collision geometry only: they carry
    # no mass and are never simulated as dynamic bodies, because their only job
    # is to be something the planner has to route around.
    for obstacle in params.obstacles:
        ET.SubElement(
            worldbody,
            "geom",
            name=f"obstacle_{obstacle.name}",
            type="box",
            pos=_vec(obstacle.pos_m),
            size=_vec(obstacle.half_size_m),
            rgba="0.45 0.35 0.30 1",
        )

    _, _, length_fore = params.link_lengths_m
    parent = worldbody

    for joint, link, origin, length, along in _chain(params):
        actuator = params.actuators[joint.actuator]
        body = ET.SubElement(parent, "body", name=link.name, pos=_vec(origin))
        # armature and damping come from the actuator, never from a hard-coded
        # default: the controller's model reads the same numbers out of the same
        # TOML, and a value only one engine knows about silently makes them
        # different robots.
        ET.SubElement(
            body,
            "joint",
            name=joint.name,
            type="hinge",
            axis=_vec(joint.axis),
            range=f"{_fmt(joint.limit_lower_rad)} {_fmt(joint.limit_upper_rad)}",
            armature=_fmt(actuator.armature_kgm2),
            damping=_fmt(actuator.damping_nms_rad),
            frictionloss=_fmt(actuator.coulomb_friction_nm),
        )
        ixx, iyy, izz = link.inertia_kgm2
        ET.SubElement(
            body,
            "inertial",
            pos=_vec(link.com_m),
            mass=_fmt(link.mass_kg),
            diaginertia=f"{_fmt(ixx)} {_fmt(iyy)} {_fmt(izz)}",
        )

        half, centre = _collision_box(length, along)
        ET.SubElement(
            body,
            "geom",
            name=f"{link.name}_collision",
            type="box",
            pos=_vec(centre),
            size=_vec(half),
            group="3",
            rgba="0.8 0.3 0.3 0.25",
        )
        if _meshes_available():
            ET.SubElement(
                body,
                "geom",
                name=f"{link.name}_visual",
                type="mesh",
                mesh=f"{link.name}_mesh",
                contype="0",
                conaffinity="0",
                group="2",
                rgba="0.62 0.66 0.72 1",
            )
        parent = body

    # Matches the URDF's ee frame so both models measure the same point.
    ET.SubElement(parent, "site", name="ee", pos=_vec((length_fore, 0.0, 0.0)), size="0.006")

    # Actuators: the thing URDF has no vocabulary for. Torque control, because
    # that is the point of choosing servos with a current-control mode.
    actuators = ET.SubElement(root, "actuator")
    for joint, *_ in _chain(params):
        limit = params.actuators[joint.actuator].continuous_torque_nm
        ET.SubElement(
            actuators,
            "motor",
            name=f"{joint.name}_motor",
            joint=joint.name,
            ctrlrange=f"{_fmt(-limit)} {_fmt(limit)}",
            gear="1",
        )

    # The pedestal is bolted to the surface it stands on, and its only freedom
    # is rotation about z -- so contact between it and the floor can never do
    # anything except cost solver time. Its bottom face sits exactly on the
    # floor plane, which produced four coincident-surface contacts on every
    # step of every simulation.
    contacts = ET.SubElement(root, "contact")
    base_link = _chain(params)[0][1]
    ET.SubElement(contacts, "exclude", body1="world", body2=base_link.name)

    sensors = ET.SubElement(root, "sensor")
    for joint, *_ in _chain(params):
        ET.SubElement(sensors, "jointpos", name=f"{joint.name}_pos", joint=joint.name)
        ET.SubElement(sensors, "jointvel", name=f"{joint.name}_vel", joint=joint.name)
    ET.SubElement(sensors, "framepos", name="ee_pos", objtype="site", objname="ee")

    return _pretty(root, _BANNER)


def write_models(params: ArmParams | None = None, directory: Path | None = None):
    """Write both descriptions; returns the paths written."""
    directory = directory or GENERATED_DIR
    directory.mkdir(parents=True, exist_ok=True)

    urdf = directory / "arm.urdf"
    mjcf = directory / "arm.xml"
    urdf.write_text(build_urdf(params))
    mjcf.write_text(build_mjcf(params))
    return urdf, mjcf
